import type { Metadata } from "next";
import Link from "next/link";
import { FileText, Lock } from "lucide-react";
import { Badge } from "@/components/ui/badge";
import { PageHeader, PageShell } from "@/components/shared/page-header";
import { EmptyState } from "@/components/shared/states";
import { LETTER_TYPE_LABELS } from "@/lib/schemas/letters";
import { requirePagePermission } from "@/server/auth/page-guards";
import { letterRecipients, listGeneratedLetters, listTemplates } from "@/server/services/letters";
import { GenerateLetterDialog } from "./generate-letter-dialog";
import { LetterStatusSelect } from "./letter-status-select";

export const metadata: Metadata = { title: "Letters & Memos" };

export default async function LettersPage() {
  const ctx = await requirePagePermission("letters.view");
  const canGenerate = ctx.permissions.has("letters.generate");
  const canSeeSalary = ctx.permissions.has("employees.salary.view");

  const [letters, templates, employees] = await Promise.all([
    listGeneratedLetters(ctx),
    canGenerate ? listTemplates(ctx) : Promise.resolve([]),
    canGenerate ? letterRecipients(ctx) : Promise.resolve([]),
  ]);

  const activeTemplates = templates
    .filter((t) => t.isActive)
    .map((t) => ({ id: t.id, name: t.name, type: t.type }));

  const recipients = employees.map((e) => ({
    id: e.id,
    label: `${e.fullName} · ${e.employeeNo} · ${e.company.code}`,
  }));

  return (
    <PageShell>
      <PageHeader
        printable
        title="Letters & Memos"
        description="Every generated letter keeps a frozen copy of the data it was built from, so it stays valid after the underlying record changes."
        action={
          canGenerate ? (
            <GenerateLetterDialog templates={activeTemplates} employees={recipients} />
          ) : null
        }
      />

      {letters.length === 0 ? (
        <EmptyState
          icon={FileText}
          title="No letters yet"
          description={
            canGenerate
              ? "Generate a letter from a template to see it here."
              : "Letters generated by HR will appear here."
          }
        />
      ) : (
        <div className="overflow-x-auto rounded-lg border">
          <table className="w-full text-sm">
            <thead className="bg-muted/40 text-muted-foreground">
              <tr>
                <th className="px-3 py-2 text-left font-medium">Letter no.</th>
                <th className="px-3 py-2 text-left font-medium">Type</th>
                <th className="px-3 py-2 text-left font-medium">Employee</th>
                <th className="px-3 py-2 text-left font-medium">Company</th>
                <th className="px-3 py-2 text-left font-medium">Generated</th>
                <th className="px-3 py-2 text-left font-medium">Status</th>
              </tr>
            </thead>
            <tbody>
              {letters.map((letter) => (
                <tr key={letter.id} className="border-t">
                  <td className="px-3 py-2">
                    {letter.containsSalary && !canSeeSalary ? (
                      // Listed but not linked: the metadata is not the secret,
                      // and saying why beats a 404 on click.
                      <span className="text-muted-foreground flex items-center gap-1.5 font-mono">
                        <Lock className="size-3.5" aria-hidden="true" />
                        {letter.letterNo}
                        <span className="sr-only">
                          — contains salary information you cannot view
                        </span>
                      </span>
                    ) : (
                      <Link
                        href={`/hr/letters/${letter.id}`}
                        target="_blank"
                        rel="noopener"
                        className="font-mono font-medium hover:underline"
                      >
                        {letter.letterNo}
                      </Link>
                    )}
                  </td>
                  <td className="px-3 py-2">
                    {LETTER_TYPE_LABELS[letter.template.type]}
                    <p className="text-muted-foreground text-xs">{letter.template.name}</p>
                  </td>
                  <td className="px-3 py-2">
                    {letter.employee ? (
                      <Link
                        href={`/people/employees/${letter.employee.id}`}
                        className="hover:underline"
                      >
                        {letter.employee.fullName}
                      </Link>
                    ) : (
                      <span className="text-muted-foreground">—</span>
                    )}
                  </td>
                  <td className="text-muted-foreground px-3 py-2">{letter.company.code}</td>
                  <td className="text-muted-foreground px-3 py-2 tabular-nums">
                    {letter.generatedAt.toISOString().slice(0, 10)}
                  </td>
                  <td className="px-3 py-2">
                    {canGenerate ? (
                      <LetterStatusSelect id={letter.id} status={letter.status} />
                    ) : (
                      <Badge variant="outline">{letter.status}</Badge>
                    )}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}
    </PageShell>
  );
}
