import * as React from "react";
import { cva, type VariantProps } from "class-variance-authority";
import { Slot } from "radix-ui";

import { cn } from "@/lib/utils";

const badgeVariants = cva(
  "inline-flex w-fit shrink-0 items-center justify-center gap-1 overflow-hidden rounded-full border px-2.5 py-0.5 text-xs font-medium whitespace-nowrap transition-[color,box-shadow] [&>svg]:pointer-events-none [&>svg]:size-3",
  {
    variants: {
      variant: {
        default: "border-transparent bg-primary text-primary-foreground",
        secondary: "border-transparent bg-secondary text-secondary-foreground",
        destructive: "border-transparent bg-destructive text-white",
        outline: "text-foreground",
        // Semantic status variants — the only sanctioned use of colour in the
        // UI. Everything structural stays greyscale, so a coloured badge in a
        // table always means something (docs/MODULES.md §6).
        valid: "border-transparent bg-status-valid-bg text-status-valid",
        warning: "border-transparent bg-status-warning-bg text-status-warning",
        expired: "border-transparent bg-status-expired-bg text-status-expired",
        info: "border-transparent bg-status-info-bg text-status-info",
        neutral: "border-transparent bg-status-neutral-bg text-status-neutral",
      },
    },
    defaultVariants: { variant: "default" },
  },
);

function Badge({
  className,
  variant,
  asChild = false,
  ...props
}: React.ComponentProps<"span"> & VariantProps<typeof badgeVariants> & { asChild?: boolean }) {
  const Comp = asChild ? Slot.Root : "span";

  return (
    <Comp data-slot="badge" className={cn(badgeVariants({ variant }), className)} {...props} />
  );
}

export { Badge, badgeVariants };
